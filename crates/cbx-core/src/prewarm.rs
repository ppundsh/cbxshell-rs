//! Bulk thumbnail pre-generation ("pre-warm") into the Windows thumbnail cache.
//!
//! Explorer asks a thumbnail handler for one item at a time, only for items that are (about to
//! be) visible, and decides itself how many requests run in parallel. A handler cannot see the
//! rest of the folder or answer in batches. What *can* be done ahead of time is to fill the
//! system thumbnail cache (`thumbcache_*.db`): `IThumbnailCache::GetThumbnail` runs the
//! registered handler (CBX Shell) for an item and stores the result exactly where Explorer looks
//! first. When the folder is opened later, Explorer finds every thumbnail in the cache and does
//! not call the handler at all.
//!
//! This module walks a folder (and up to [`MAX_PREWARM_DEPTH`] levels of sub-folders), keeps the
//! files whose extension is associated with CBX Shell, and requests their thumbnails from
//! several worker threads in parallel.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};

use windows::core::{GUID, PCWSTR};
use windows::Win32::System::Com::{
    CoCreateInstance, CoInitializeEx, CoUninitialize, CLSCTX_INPROC_SERVER, COINIT_MULTITHREADED,
};
use windows::Win32::System::Registry::{HKEY_CURRENT_USER, HKEY_LOCAL_MACHINE};
use windows::Win32::UI::Shell::{
    IShellItem, IThumbnailCache, SHChangeNotify, SHCreateItemFromParsingName, SHCNE_UPDATEDIR, SHCNF_FLUSHNOWAIT,
    SHCNF_PATHW, WTS_FORCEEXTRACTION,
};

/// Sub-folder levels below the dropped folder that are included.
pub const MAX_PREWARM_DEPTH: usize = 3;
/// Hard cap on the number of files of one run.
pub const MAX_PREWARM_FILES: usize = 200_000;

/// CLSID_LocalThumbnailCache = {50ef4544-ac9f-4a8e-b21b-8a26180db13f}
const CLSID_LOCAL_THUMBNAIL_CACHE: GUID = GUID::from_u128(0x50ef4544_ac9f_4a8e_b21b_8a26180db13f);
/// `WTS_CACHED` bit of `WTS_CACHEFLAGS`: the thumbnail already came from the cache.
const WTS_CACHED_BIT: i64 = 0x2;

const FILE_ATTRIBUTE_HIDDEN: u32 = 0x2;
const FILE_ATTRIBUTE_SYSTEM: u32 = 0x4;
const FILE_ATTRIBUTE_REPARSE_POINT: u32 = 0x400;

#[derive(Clone, Debug)]
pub struct PrewarmOptions {
    /// Requested thumbnail size in pixels (Explorer buckets: 96 medium, 256 large, 768 extra large).
    pub size: u32,
    /// Re-extract even when the cache already has the item.
    pub force: bool,
    /// Worker threads (clamped to 1..=16).
    pub threads: usize,
    /// Sub-folder levels to include (clamped to `MAX_PREWARM_DEPTH`).
    pub max_depth: usize,
}

/// Live counters shared with the UI thread.
#[derive(Default)]
pub struct PrewarmProgress {
    pub scanning: AtomicBool,
    pub running: AtomicBool,
    pub cancel: AtomicBool,
    pub total: AtomicUsize,
    pub done: AtomicUsize,
    /// Newly generated by the handler.
    pub generated: AtomicUsize,
    /// Already in the cache (skipped without calling the handler).
    pub cached: AtomicUsize,
    pub failed: AtomicUsize,
    pub elapsed_ms: AtomicUsize,
    pub current: Mutex<String>,
    pub root: Mutex<String>,
}

impl PrewarmProgress {
    pub fn is_active(&self) -> bool {
        self.scanning.load(Ordering::Acquire) || self.running.load(Ordering::Acquire)
    }
}

/// Default worker count: half the logical CPUs, 2..=8.
pub fn default_threads() -> usize {
    std::thread::available_parallelism()
        .map(|n| n.get() / 2)
        .unwrap_or(2)
        .clamp(2, 8)
}

fn ext_of(p: &Path) -> String {
    p.extension()
        .and_then(|e| e.to_str())
        .map(|e| format!(".{}", e.to_ascii_lowercase()))
        .unwrap_or_default()
}

/// Lists files below `root` (depth 0 = the folder itself) whose extension passes `wanted`.
/// Hidden / system entries and reparse points (junctions, symlinks) are skipped so the walk can
/// never loop or wander outside the chosen tree.
pub fn collect_targets(
    root: &Path,
    max_depth: usize,
    cancel: &AtomicBool,
    mut wanted: impl FnMut(&str) -> bool,
) -> Vec<PathBuf> {
    use std::os::windows::fs::MetadataExt;
    let max_depth = max_depth.min(MAX_PREWARM_DEPTH);
    let mut out = Vec::new();
    let mut stack: Vec<(PathBuf, usize)> = vec![(root.to_path_buf(), 0)];
    while let Some((dir, depth)) = stack.pop() {
        if cancel.load(Ordering::Relaxed) || out.len() >= MAX_PREWARM_FILES {
            break;
        }
        let Ok(rd) = std::fs::read_dir(&dir) else {
            continue;
        };
        let mut subdirs = Vec::new();
        let mut files = Vec::new();
        for entry in rd.flatten() {
            let Ok(md) = entry.metadata() else {
                continue;
            };
            let attrs = md.file_attributes();
            if attrs & (FILE_ATTRIBUTE_HIDDEN | FILE_ATTRIBUTE_SYSTEM | FILE_ATTRIBUTE_REPARSE_POINT) != 0 {
                continue;
            }
            let path = entry.path();
            if md.is_dir() {
                if depth < max_depth {
                    subdirs.push(path);
                }
            } else if md.is_file() && wanted(&ext_of(&path)) {
                files.push(path);
            }
        }
        // Natural-ish order: files of a folder first, in name order, then its sub-folders.
        files.sort();
        out.extend(files.into_iter().take(MAX_PREWARM_FILES.saturating_sub(out.len())));
        subdirs.sort();
        for d in subdirs.into_iter().rev() {
            stack.push((d, depth + 1));
        }
    }
    out
}

fn wide(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(std::iter::once(0)).collect()
}

/// Starts a pre-warm run on background threads and returns immediately.
pub fn start(root: PathBuf, opts: PrewarmOptions, progress: Arc<PrewarmProgress>) {
    progress.cancel.store(false, Ordering::Release);
    progress.total.store(0, Ordering::Release);
    progress.done.store(0, Ordering::Release);
    progress.generated.store(0, Ordering::Release);
    progress.cached.store(0, Ordering::Release);
    progress.failed.store(0, Ordering::Release);
    progress.elapsed_ms.store(0, Ordering::Release);
    if let Ok(mut r) = progress.root.lock() {
        *r = root.to_string_lossy().into_owned();
    }
    progress.scanning.store(true, Ordering::Release);

    std::thread::spawn(move || {
        let started = std::time::Instant::now();
        // Only extensions Explorer actually routes to CBX Shell; anything else would be
        // answered by another handler and is not ours to warm.
        let mut assoc: HashMap<String, bool> = HashMap::new();
        let targets = collect_targets(&root, opts.max_depth, &progress.cancel, |ext| {
            if ext.is_empty() {
                return false;
            }
            *assoc.entry(ext.to_string()).or_insert_with(|| {
                crate::registry::is_associated(HKEY_CURRENT_USER, ext)
                    || crate::registry::is_associated(HKEY_LOCAL_MACHINE, ext)
            })
        });
        progress.total.store(targets.len(), Ordering::Release);
        progress.running.store(true, Ordering::Release);
        progress.scanning.store(false, Ordering::Release);

        let targets = Arc::new(targets);
        let next = Arc::new(AtomicUsize::new(0));
        let threads = opts.threads.clamp(1, 16).min(targets.len().max(1));
        let mut handles = Vec::with_capacity(threads);
        for _ in 0..threads {
            let targets = Arc::clone(&targets);
            let next = Arc::clone(&next);
            let progress = Arc::clone(&progress);
            let opts = opts.clone();
            handles.push(std::thread::spawn(move || worker(&targets, &next, &progress, &opts)));
        }
        for h in handles {
            let _ = h.join();
        }

        // Let open windows of that folder pick the new thumbnails up.
        let root_w = wide(&root.to_string_lossy());
        // SAFETY: NUL-terminated path buffer that outlives the call.
        unsafe {
            SHChangeNotify(SHCNE_UPDATEDIR, SHCNF_PATHW | SHCNF_FLUSHNOWAIT, Some(root_w.as_ptr().cast()), None);
        }
        progress
            .elapsed_ms
            .store(started.elapsed().as_millis().min(usize::MAX as u128) as usize, Ordering::Release);
        if let Ok(mut c) = progress.current.lock() {
            c.clear();
        }
        progress.running.store(false, Ordering::Release);
    });
}

fn worker(targets: &[PathBuf], next: &AtomicUsize, progress: &PrewarmProgress, opts: &PrewarmOptions) {
    // SAFETY: COM is initialised for this worker thread only and released before it exits.
    unsafe {
        let inited = CoInitializeEx(None, COINIT_MULTITHREADED).is_ok();
        let cache: Option<IThumbnailCache> =
            CoCreateInstance(&CLSID_LOCAL_THUMBNAIL_CACHE, None, CLSCTX_INPROC_SERVER).ok();
        loop {
            if progress.cancel.load(Ordering::Acquire) {
                break;
            }
            let i = next.fetch_add(1, Ordering::AcqRel);
            let Some(path) = targets.get(i) else {
                break;
            };
            if let Ok(mut c) = progress.current.lock() {
                *c = path
                    .file_name()
                    .map(|n| n.to_string_lossy().into_owned())
                    .unwrap_or_default();
            }
            let ok = match &cache {
                Some(cache) => {
                    let w = wide(&path.to_string_lossy());
                    let item: windows::core::Result<IShellItem> = SHCreateItemFromParsingName(PCWSTR(w.as_ptr()), None);
                    match item {
                        Ok(item) => {
                            let mut bmp = None;
                            let mut out_flags = Default::default();
                            let mut id = Default::default();
                            let flags = if opts.force { WTS_FORCEEXTRACTION } else { Default::default() };
                            match cache.GetThumbnail(&item, opts.size, flags, Some(&mut bmp), Some(&mut out_flags), Some(&mut id)) {
                                Ok(()) => {
                                    let out_flags: windows::Win32::UI::Shell::WTS_CACHEFLAGS = out_flags;
                                    if !opts.force && (out_flags.0 as i64 & WTS_CACHED_BIT) != 0 {
                                        progress.cached.fetch_add(1, Ordering::AcqRel);
                                    } else {
                                        progress.generated.fetch_add(1, Ordering::AcqRel);
                                    }
                                    true
                                }
                                Err(_) => false,
                            }
                        }
                        Err(_) => false,
                    }
                }
                None => false,
            };
            if !ok {
                progress.failed.fetch_add(1, Ordering::AcqRel);
            }
            progress.done.fetch_add(1, Ordering::AcqRel);
        }
        drop(cache);
        if inited {
            CoUninitialize();
        }
    }
}
